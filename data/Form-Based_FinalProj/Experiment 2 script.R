library(lmerTest)
library(multcomp)
E2A = read.table("Exp2.txt",TRUE)
E2 = subset(E2A,Accuracy==1)
E2$WordType = factor(E2$WordType,levels=c("control","attractor","target"))
E2$Subject = factor(E2$Subject)
E2$Item = factor(E2$Item)
e2a = lmer(Rating~WordType+(1|Subject)+(1|Item),data=E2,REML=F,control=lmerControl(optimizer="bobyqa",optCtrl=list(maxfun=1e6)))
e2b = lmer(Rating~WordType+(WordType+1|Subject)+(1|Item),data=E2,REML=F,control=lmerControl(optimizer="bobyqa",optCtrl=list(maxfun=1e6)))
e2c = lmer(Rating~WordType+(1|Subject)+(WordType+1|Item),data=E2,REML=F,control=lmerControl(optimizer="bobyqa",optCtrl=list(maxfun=1e6)))
anova(e2a,e2b)
anova(e2a,e2c)
e2 = lmer(Rating~WordType+(WordType+1|Subject)+(WordType+1|Item),data=E2,REML=F,control=lmerControl(optimizer="bobyqa",optCtrl=list(maxfun=1e6)))
summary(e2)
e2pw = glht(e2, linfct = mcp(WordType = "Tukey"))
summary(e2pw, test = adjusted("none"))
