library(lmerTest)
library(multcomp)
E1A = read.table("./data/Form-Based_FinalProj/Exp1.txt",TRUE)
E1 = subset(E1A,Knowledgeable==0)
E1$WordType = factor(E1$WordType,levels=c("control","implied","attractor","target"))
E1$Subject = factor(E1$Subject)
E1$Item = factor(E1$Item)
e1a = lmer(Response~WordType+(1|Subject)+(1|Item),data=E1,REML=F,control=lmerControl(optimizer="bobyqa",optCtrl=list(maxfun=1e6)))
e1b = lmer(Response~WordType+(WordType+1|Subject)+(1|Item),data=E1,REML=F,control=lmerControl(optimizer="bobyqa",optCtrl=list(maxfun=1e6)))
e1c = lmer(Response~WordType+(1|Subject)+(WordType+1|Item),data=E1,REML=F,control=lmerControl(optimizer="bobyqa",optCtrl=list(maxfun=1e6)))
anova(e1a,e1c)
e1 = lmer(Response~WordType+(1|Subject)+(WordType+1|Item),data=E1,REML=F,control=lmerControl(optimizer="bobyqa",optCtrl=list(maxfun=1e6)))
summary(e1)
e1pw = glht(e1, linfct = mcp(WordType = "Tukey"))
summary(e1pw, test = adjusted("none"))
